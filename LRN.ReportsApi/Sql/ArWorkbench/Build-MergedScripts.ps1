<#
  Regenerates the two merged AR Workbench setup scripts from the numbered scripts in this folder:

    ARWB_Lab_Database_Setup_Merged.sql   run in EACH LAB database     = 01, 02, 03, 04, 05, 06, 07, 09
    ARWB_LRNMaster_Setup_Merged.sql      run ONCE in LRNMaster          = LRNMaster_01, _02, _03

  Left out on purpose (run them on their own when needed):
    00_ARWB_Drop_Existing_Objects.sql    destructive - drops every workbench object and its data
    08_ARWB_Optional_SourceIndex.sql     optional index on the dbo.LineLevelData source table
    RUN_InHealth_Initial_Setup.sql       one lab's first-time setup

  Edit the numbered scripts, then run:   .\Build-MergedScripts.ps1
  Every script is idempotent, so a merged file can be re-run safely.
#>
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$utf8Bom = New-Object System.Text.UTF8Encoding($true)

function Build-Merged([string]$target, [string[]]$parts, [string]$title, [string]$runIn, [string]$after) {
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine('/* ============================================================================================')
    [void]$sb.AppendLine("   AR Workbench - $title (merged)")
    [void]$sb.AppendLine("   GENERATED by Build-MergedScripts.ps1 from: $($parts -join ', ')")
    [void]$sb.AppendLine('   Edit those scripts and regenerate; do not edit this file.')
    [void]$sb.AppendLine("   Run in: $runIn")
    if ($after) { foreach ($line in $after -split "`n") { [void]$sb.AppendLine("   $line") } }
    [void]$sb.AppendLine('   Every part is idempotent: safe to run again.')
    [void]$sb.AppendLine('   ============================================================================================ */')
    [void]$sb.AppendLine()
    foreach ($part in $parts) {
        $path = Join-Path $here $part
        if (-not (Test-Path $path)) { throw "Missing $part" }
        $text = [IO.File]::ReadAllText($path, [Text.Encoding]::UTF8).TrimStart([char]0xFEFF).Replace("`r`n", "`n").TrimEnd()
        [void]$sb.AppendLine("-- >>>>>>>>>>>>>>>>>>>> $part")
        [void]$sb.AppendLine($text)
        # Each part must end its last batch, so the next file starts a new one.
        $lastLine = ($text -split "`n")[-1].Trim()
        if ($lastLine -notmatch '^GO\b') { [void]$sb.AppendLine('GO') }
        [void]$sb.AppendLine()
    }
    [void]$sb.AppendLine("PRINT 'AR Workbench ${title}: all parts ran.';")
    [void]$sb.AppendLine('GO')
    $out = $sb.ToString().Replace("`r`n", "`n").Replace("`n", "`r`n")
    [IO.File]::WriteAllText((Join-Path $here $target), $out, $utf8Bom)
    Write-Output ("{0}: {1} parts, {2:N0} lines" -f $target, $parts.Count, ($out -split "`n").Count)
}

Build-Merged 'ARWB_Lab_Database_Setup_Merged.sql' @(
    '01_ARWB_Tables.sql', '02_ARWB_Functions.sql', '03_ARWB_MasterData_Seed.sql', '04_ARWB_ClaimState_Procedure.sql',
    '05_ARWB_LoadFromSource_Procedure.sql', '06_ARWB_Workflow_Procedures.sql', '07_ARWB_Views.sql', '09_ARWB_Legacy_Cip_Conversion.sql'
) 'LAB DATABASE SETUP' 'each LAB database (the one holding dbo.ClaimLevelData / dbo.LineLevelData).' (
    "Run ARWB_LRNMaster_Setup_Merged.sql in LRNMaster first (roles, users' scope, denial code master, client activation).`n" +
    "To rebuild from clean, run 00_ARWB_Drop_Existing_Objects.sql first (it deletes all workbench data).`n" +
    "Optional: 08_ARWB_Optional_SourceIndex.sql (index on dbo.LineLevelData).`n" +
    "Then load the claims:  EXEC dbo.ARWB_usp_LoadClaimsFromSource @RunBy = N'your.name', @Note = N'Initial load';")

