    @{ Name='BeechTree';        Folder='BeechTree';        Prefix='BT';   PanelCol='Panelname';     HasBilledUnbilled=$true;  HasAgingBucket=$true;  FileNo=12 },
    @{ Name='Certus';           Folder='Certus';           Prefix='Cert'; PanelCol='Panelname';     HasBilledUnbilled=$false; HasAgingBucket=$false; FileNo=11 },
    @{ Name='Cove';             Folder='Cove';             Prefix='Cove'; PanelCol='Panelname';     HasBilledUnbilled=$false; HasAgingBucket=$false; FileNo=12 },
    @{ Name='Elixir';           Folder='Elixir';           Prefix='Elix'; PanelCol='Panelname';     HasBilledUnbilled=$false; HasAgingBucket=$false; FileNo=12 },
    @{ Name='NorthWest';        Folder='NorthWest';        Prefix='NW';   PanelCol='PanelType';     HasBilledUnbilled=$false; HasAgingBucket=$false; FileNo=11 },
