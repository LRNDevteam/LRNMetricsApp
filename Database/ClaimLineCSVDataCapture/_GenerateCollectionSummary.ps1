#
# Per-lab variations handled for the remaining 6 labs:
#   - Stored-proc / table prefix (BT, Cert, Cove, Elix, NW, PCR)
#   - Panel column name           (Panelname / PanelType / PanelCategory)
#   - Whether BilledUnbilled exists in dbo.ClaimLevelData
#   - Whether AgingBucket exists in dbo.ClaimLevelData
#       Fallbacks when missing:
#         * BilledUnbilled half of the "No Response & Unbilled" exclusion
#           is dropped (only ClaimStatus='No Response' is excluded).
#         * AgingBucket = '30 Days' / '60 Days' becomes
#           DaystoDOS BETWEEN 30 AND 59 / 60 AND 89.
#
# Re-run any time the RisingTides template changes.
# =====================================================================

