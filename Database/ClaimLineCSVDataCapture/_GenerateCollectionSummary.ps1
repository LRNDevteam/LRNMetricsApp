# =====================================================================
# Generates the per-lab Collection Summary SQL file
# (tables + stored procedures) for the labs listed below, using the
# RisingTides version (13_RisingTides_CollectionSummary.sql) as the template.
#
# Augustus is excluded here — it has a fully hand-crafted file at
# Sql\Augustus\13_Augustus_CollectionSummary.sql that uses pre-computed
# columns (Bucket30, Bucket60, Adjudicated, etc.) and ClaimLevelData
