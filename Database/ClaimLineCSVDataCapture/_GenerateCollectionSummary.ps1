        $bucket30 = "Bucket = '30 Days'"
        $bucket60 = "Bucket = '60 Days'"
        $bucketSel = "LTRIM(RTRIM(AgingBucket))"
    } else {
        $bucket30 = "Days BETWEEN 30 AND 59"
        $bucket60 = "Days BETWEEN 60 AND 89"
        $bucketSel = "ISNULL(TRY_CAST(DaystoDOS AS INT), -1)"
    }

    $billedSel = if ($lab.HasBilledUnbilled) { "LTRIM(RTRIM(BilledUnbilled))" } else { "CAST(NULL AS NVARCHAR(100))" }
    $bucketAlias = if ($lab.HasAgingBucket) { "Bucket" } else { "Days" }

