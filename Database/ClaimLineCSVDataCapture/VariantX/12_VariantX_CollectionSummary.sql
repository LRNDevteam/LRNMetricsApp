CREATE OR ALTER PROCEDURE dbo.usp_RefreshVarX_CS_InsuranceVsPayment
AS
BEGIN
    SET NOCOUNT ON;

    ;WITH agg AS
    (
        SELECT
            LTRIM(RTRIM(ISNULL(PayerName_Raw, 'Unknown')))              AS PayerName,

            YEAR (TRY_CAST(CheckDate AS DATE))                          AS BillYear,
            MONTH(TRY_CAST(CheckDate AS DATE))                          AS BillMonth,

            COUNT(DISTINCT NULLIF(LTRIM(RTRIM(ClaimID)), ''))  AS NoOfPaidClaims,

            ISNULL(
                SUM(TRY_CAST(InsurancePayment AS DECIMAL(18,2))),
                0
            )                                                           AS InsurancePayment

        -- Client sheet: Claim Level Data, InsurancePayment > 0, CheckDate is a date.
        FROM dbo.ClaimLevelData
        WHERE
            ISNULL(TRY_CAST(InsurancePayment AS DECIMAL(18,2)), 0) > 0
            AND NULLIF(LTRIM(RTRIM(CheckDate)), '') IS NOT NULL
            AND TRY_CAST(CheckDate AS DATE) IS NOT NULL
            AND YEAR(TRY_CAST(CheckDate AS DATE)) > 1900

        GROUP BY
            LTRIM(RTRIM(ISNULL(PayerName_Raw, 'Unknown'))),
            YEAR (TRY_CAST(CheckDate AS DATE)),
            MONTH(TRY_CAST(CheckDate AS DATE))
    ),

    grand AS
    (
        SELECT
            BillYear,
            BillMonth,
            NULLIF(SUM(InsurancePayment), 0) AS TotalInsurancePayment
        FROM agg
        GROUP BY
            BillYear,
            BillMonth
    )

    SELECT
        a.PayerName,
        CAST(a.BillYear  AS SMALLINT)  AS BillYear,
        CAST(a.BillMonth AS TINYINT)   AS BillMonth,
        a.NoOfPaidClaims,
        a.InsurancePayment,
        CAST
        (
            a.InsurancePayment * 100.0 /
            ISNULL(g.TotalInsurancePayment, 1)
            AS DECIMAL(9,4)
        )                              AS PaymentPct

    INTO #out
    FROM agg a
    INNER JOIN grand g
        ON  a.BillYear  = g.BillYear
        AND a.BillMonth = g.BillMonth;

    TRUNCATE TABLE dbo.VarX_CS_InsuranceVsPayment;

    INSERT INTO dbo.VarX_CS_InsuranceVsPayment
    (
        PayerName,
        BillYear,
        BillMonth,
        NoOfPaidClaims,
        InsurancePayment,
        PaymentPct,
        RefreshedAt
    )
    SELECT
        PayerName,
        BillYear,
        BillMonth,
        NoOfPaidClaims,
        InsurancePayment,
        PaymentPct,
        GETDATE()
    FROM #out
    ORDER BY
        BillYear,
        BillMonth,
        InsurancePayment DESC;

    DROP TABLE IF EXISTS #out;

    PRINT 'usp_RefreshVarX_CS_InsuranceVsPayment completed.';
END
GO
