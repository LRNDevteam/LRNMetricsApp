<#
  Regenerates the two merged AR Workbench setup scripts from the numbered scripts in the
  LRNMaster\ and LabDatabase\ sub-folders. Run them in this order:

    1_RUN_IN_LRNMASTER_ARWB_Setup.sql      run ONCE in LRNMaster          = LRNMaster\LRNMaster_01, _02, _03, _04
    2_RUN_IN_EACH_LAB_DB_ARWB_Setup.sql    run in EACH LAB database       = LabDatabase\01, 02, 03, 04, 05, 06, 07, 09

  Left out on purpose (run them on their own when needed):
    LabDatabase\00_ARWB_Drop_Existing_Objects.sql   destructive - drops every workbench object and its data
    LabDatabase\08_ARWB_Optional_SourceIndex.sql    optional index on the dbo.LineLevelData source table
    RUN_InHealth_Initial_Setup.sql                  one lab's first-time setup (SQLCMD, both databases)

  Edit the numbered scripts, then run:   .\Build-MergedScripts.ps1
  Every script is idempotent, so a merged file can be re-run safely.
#>
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$utf8Bom = New-Object System.Text.UTF8Encoding($true)

function Build-Merged([string]$target, [string[]]$parts, [string]$title, [string]$runIn, [string]$after) {
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine('/* ============================================================================================')
    [void]$sb.AppendLine("   AR Workbench - $title (merged)")
    [void]$sb.AppendLine("   GENERATED by Build-MergedScripts.ps1 from: $($parts -join ', ')")
    [void]$sb.AppendLine('   Edit those scripts and regenerate; do not edit this file.')
    [void]$sb.AppendLine("   Run in: $runIn")
    if ($after) { foreach ($line in $after -split "`n") { [void]$sb.AppendLine("   $line") } }
    [void]$sb.AppendLine('   Every part is idempotent: safe to run again.')
    [void]$sb.AppendLine('   ============================================================================================ */')
    [void]$sb.AppendLine()
    foreach ($part in $parts) {
        $path = Join-Path $here $part
        if (-not (Test-Path $path)) { throw "Missing $part" }
        $text = [IO.File]::ReadAllText($path, [Text.Encoding]::UTF8).TrimStart([char]0xFEFF).Replace("`r`n", "`n").TrimEnd()
        [void]$sb.AppendLine("-- >>>>>>>>>>>>>>>>>>>> $part")
        [void]$sb.AppendLine($text)
        # Each part must end its last batch, so the next file starts a new one.
        $lastLine = ($text -split "`n")[-1].Trim()
        if ($lastLine -notmatch '^GO\b') { [void]$sb.AppendLine('GO') }
        [void]$sb.AppendLine()
    }
    [void]$sb.AppendLine("PRINT 'AR Workbench ${title}: all parts ran.';")
    [void]$sb.AppendLine('GO')
    $out = $sb.ToString().Replace("`r`n", "`n").Replace("`n", "`r`n")
    [IO.File]::WriteAllText((Join-Path $here $target), $out, $utf8Bom)
    Write-Output ("{0}: {1} parts, {2:N0} lines" -f $target, $parts.Count, ($out -split "`n").Count)
}

Build-Merged '1_RUN_IN_LRNMASTER_ARWB_Setup.sql' @(
    'LRNMaster\LRNMaster_01_ARWB_Roles_Access.sql', 'LRNMaster\LRNMaster_02_ARWB_DenialCodeMaster.sql', 'LRNMaster\LRNMaster_03_ARWB_ClientSetting.sql',
    'LRNMaster\LRNMaster_04_ARDocumentTypeMaster.sql'
) 'LRNMASTER SETUP' 'LRNMaster (DefaultConnection), once per environment - before the lab scripts.' (
    "Requires dbo.RoleFeatureAccess (Database/LRN.ReportsApi/DynamicMenu_Setup.sql).`n" +
    "Then run 2_RUN_IN_EACH_LAB_DB_ARWB_Setup.sql in each lab database.")

Build-Merged '2_RUN_IN_EACH_LAB_DB_ARWB_Setup.sql' @(
    'LabDatabase\01_ARWB_Tables.sql', 'LabDatabase\02_ARWB_Functions.sql', 'LabDatabase\03_ARWB_MasterData_Seed.sql',
